Param(
  [string]$Version = "",
  [string]$Root = "",
  [switch]$IncrementBuild,
  [switch]$NoWriteLock
)

$ErrorActionPreference = "Stop"
if (-not $Root) {
  $Root = Split-Path -Parent $PSScriptRoot
}

$versionFile = Join-Path $Root "VERSION"
$lockFile = Join-Path $Root "version.lock.json"

if ($Version) {
  $semver = $Version.Trim()
}
elseif (Test-Path $versionFile) {
  $semver = (Get-Content $versionFile -Raw).Trim()
}
else {
  throw "VERSION file missing. Create VERSION (e.g. 1.0.0) or pass -Version."
}

if ($semver -notmatch '^\d+\.\d+\.\d+(-[A-Za-z0-9.]+)?$') {
  throw "Invalid semver in VERSION: '$semver' (expected 1.2.3 or 1.2.3-beta.1)"
}

$lock = @{
  build            = 0
  lastBuiltAt      = $null
  lastGit          = $null
  lastFullVersion  = $null
}
if (Test-Path $lockFile) {
  $lock = Get-Content $lockFile -Raw | ConvertFrom-Json
}

$buildNum = [int]$lock.build
if ($IncrementBuild) {
  $buildNum += 1
}

$git = ""
try {
  $git = (git -C $Root rev-parse --short HEAD 2>$null)
  if ($LASTEXITCODE -ne 0) { $git = "" }
} catch {
  $git = ""
}

$builtAt = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
$fullVersion = if ($buildNum -gt 0) { "$semver+$buildNum" } else { $semver }

$buildInfo = @{
  version     = $semver
  build       = $buildNum
  fullVersion = $fullVersion
  builtAt     = $builtAt
  git         = $git
}

if (-not $NoWriteLock) {
  $lockObj = @{
    build           = $buildNum
    lastBuiltAt     = $builtAt
    lastGit         = $git
    lastFullVersion = $fullVersion
  }
  $lockObj | ConvertTo-Json -Depth 4 | Set-Content -Path $lockFile -Encoding UTF8
}

# Cargo.toml (Tauri package version)
$cargoToml = Join-Path $Root "src-tauri\Cargo.toml"
if (Test-Path $cargoToml) {
  $cargo = Get-Content $cargoToml -Raw
  $cargo = $cargo -replace '(?m)^version = ".*"$', "version = `"$semver`""
  [System.IO.File]::WriteAllText($cargoToml, $cargo)
}

# frontend/package.json
$fePkg = Join-Path $Root "frontend\package.json"
if (Test-Path $fePkg) {
  $pkgRaw = Get-Content $fePkg -Raw
  $pkgRaw = $pkgRaw -replace '"version"\s*:\s*"[^"]*"', "`"version`": `"$semver`""
  [System.IO.File]::WriteAllText($fePkg, $pkgRaw)
}

# Runtime build info (Vite public + TS import)
$publicDir = Join-Path $Root "frontend\public"
New-Item -ItemType Directory -Force -Path $publicDir | Out-Null
$buildInfo | ConvertTo-Json -Depth 4 | Set-Content -Path (Join-Path $publicDir "build-info.json") -Encoding UTF8

$genDir = Join-Path $Root "frontend\src\generated"
New-Item -ItemType Directory -Force -Path $genDir | Out-Null
$ts = @"
/** Auto-generated by scripts/sync-version.ps1 — do not edit. */
export const BUILD_INFO = {
  version: '$semver',
  build: $buildNum,
  fullVersion: '$fullVersion',
  builtAt: '$builtAt',
  git: '$git',
} as const
"@
Set-Content -Path (Join-Path $genDir "build-info.ts") -Value $ts -Encoding UTF8

Write-Host "Version sync: $fullVersion (build $buildNum)" -ForegroundColor Cyan
if ($git) { Write-Host "  git: $git" -ForegroundColor DarkGray }

# Emit for callers
return @{
  Semver      = $semver
  Build       = $buildNum
  FullVersion = $fullVersion
  BuiltAt     = $builtAt
  Git         = $git
}
